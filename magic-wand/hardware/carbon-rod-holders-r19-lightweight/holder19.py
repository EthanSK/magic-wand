def bar_plan(cap_y, x_keel, x_chord, chord_depth=.2):
    """+X half of one cross bar, as an XY polygon. Print-up is -Y.

    Two 45-degree wedges grow from the keel and the chord, meet at the centre, then close into a strip of
    strip_y_mm ending at cap_y. No layer starts over air, and the opening below it has a pointed top."""
    run = (x_chord - x_keel) / 2; strip = RIB['strip_y_mm']; root = cap_y + strip + run; apex = (x_keel + x_chord) / 2
    return mf.CrossSection([base.ccw([(x_keel - .2, root), (x_keel, root), (apex, root - run), (x_chord, root), (x_chord + chord_depth, root), (x_chord + chord_depth, cap_y), (x_keel - .2, cap_y)])])


def gusset_plan(x_start, width, cap_y, x_keel):
    """+X half of a short 45-degree strut rising from the top of the last bar onto the keel under the near ring."""
    y0 = cap_y + .2; run = x_start + width - x_keel
    return mf.CrossSection([base.ccw([(x_start, y0), (x_start + width, y0), (x_keel, y0 - run), (x_keel - width, y0 - run)])]) ^ rect(0, 40, -1e3, 1e3)


def mirrored_solid(plan, z0, z1):
    solid = mf.Manifold.extrude(plan, z1 - z0).translate((0, 0, z0))
    return solid + solid.mirror((1, 0, 0))


def wall_top_profile():
    """(y, z) along the top of a side wall, from the near end to the end plate: full height under the arrow roof, then teeth."""
    lv = base.cage_levels(); rt = lv['roof_top']; v = B19['wall_valley_z_mm']; f = B19['tooth_flat_half_y_mm']; d = rt - v; start = CAGE['wall_start_y_mm']; root = B19['arrow_root_y_mm']
    pts = [(start, rt), (root, rt)]
    for c in B19['tooth_centres_y_mm']:
        rise = c - f - d; last = pts[-1]
        if last[1] == rt:
            if rise <= last[0] + d:  # Too close to the previous full-height run for a valley: stay at full height.
                pts[-1] = (c + f, rt); pts.append((c + f + d, v)); continue
            pts.append((last[0] + d, v))
        assert rise >= pts[-1][0] - 1e-6, ('teeth overlap', c)
        if rise > pts[-1][0] + 1e-6: pts.append((rise, v))
        pts += [(c - f, rt), (c + f, rt), (c + f + d, v)]
    return pts


def tooth_solid(c):
    """Retaining tooth: flange and wall tip, with 45-degree faces along Y so every layer grows on the last."""
    lv = base.cage_levels(); rb, rt = lv['roof_bottom'], lv['roof_top']; xi = CAGE['side_rail_x_mm'][0]; xo = B19['wall_outer_x_mm']; tip = B19['tooth_inner_x_mm']; ht = B19['tooth_tip_half_y_mm']; f = B19['tooth_flat_half_y_mm']; v = B19['wall_valley_z_mm']; d = rt - v; run = xi - tip
    hb = ht + run
    plan = prism_xy([(tip, c - ht), (xi + .05, c - hb - .05), (xi + .05, c + hb + .05), (tip, c + ht)], rb, rt)
    elev = prism_yz([(c - f - d, v), (c - f, rt), (c + f, rt), (c + f + d, v)], tip - 1, xo)
    solid = plan ^ elev
    ch = B19['tooth_chamfer_mm']
    return solid - prism_xz([(tip - .1, rb - .1), (tip + ch, rb - .1), (tip - .1, rb + ch + .1)], c - hb - 1, c + hb + 1)


@lru_cache(maxsize=1)
def battery_module():
    """Open cell cage: low continuous walls, central keel, arrow-windowed cross bars, retaining teeth, end frame and the R18 door interface."""
    c = CAGE; lv = base.cage_levels(); a = P['arrow_ring']; fb, ft, rb, rt = lv['floor_bottom'], lv['floor_top'], lv['roof_bottom'], lv['roof_top']
    xi = c['side_rail_x_mm'][0]; xo = B19['wall_outer_x_mm']; near0, near1 = c['near_band_y_mm']; far0, far1 = c['far_band_y_mm']; guide_y0, guide_y1 = c['guide_y_mm']; g0 = c['guide_x_mm'][0]; g1 = B19['guide_outer_x_mm']; start = c['wall_start_y_mm']
    kx = B19['keel_half_x_mm']; rz0, rz1 = B19['rib_z_mm']; wz0 = B19['wall_bottom_z_mm']; p0, p1 = B19['plate_y_mm']; sd = B19['far_flank_half_x_mm']; maxh = a['saddle_max_half_width_mm']
    pieces = [box(-kx, kx, near0, far1, fb, ft)]
    g = B19['ring_gusset']; plans = [bar_plan(y, kx, xi) for y in B19['bar_cap_y_mm']] + [gusset_plan(g['start_x_mm'], g['width_x_mm'], B19['bar_cap_y_mm'][-1], kx)]
    bars = mirrored_solid(mf.CrossSection.batch_boolean(plans, mf.OpType.Add), rz0, rz1); ch = B19['bar_chamfer_mm']
    # Lead-in on the near-end top edge of each bar, so a cell or spacer sliding toward the far end rides up instead of catching.
    for y in B19['bar_cap_y_mm']: bars -= prism_yz([(y - .05, rz1 - ch - .05), (y + ch + .05, rz1 + .05), (y - .05, rz1 + .05)], -xi - .1, xi + .1) - box(-kx, kx, -40, 40, 0, 20)
    pieces.append(bars)
    profile = wall_top_profile()
    for sign in (1, -1):
        x0, x1 = sorted([sign * xi, sign * xo])
        pieces.append(prism_yz(profile + [(p0 + .05, B19['wall_valley_z_mm']), (p0 + .05, wz0), (start, wz0)], x0, x1))
        lead = box(x0, x1, guide_y1, guide_y1 + (g1 - g0 - (xo - xi)), fb, rt); block = box(min(sign * g0, sign * g1), max(sign * g0, sign * g1), guide_y0, guide_y1, fb, rt)
        pieces.append(mf.Manifold.batch_hull([lead, block]))
        s0, s1 = B19['stop_x_mm']; pieces.append(box(min(sign * s0, sign * s1), max(sign * s0, sign * s1), lv['half_l'], p0 + .1, ft, ft + P['cell']['manufacturer_max_mm']['thickness']))
        for t in B19['tooth_centres_y_mm']:
            tooth = tooth_solid(t); pieces.append(tooth if sign > 0 else tooth.mirror((1, 0, 0)))
    w = B19['window']; plate = box(-xo, xo, p0, p1, fb, rt) - prism_xz([(-w['half_x_mm'], w['z0_mm']), (w['half_x_mm'], w['z0_mm']), (w['half_x_mm'], w['shoulder_z_mm']), (0, w['apex_z_mm']), (-w['half_x_mm'], w['shoulder_z_mm'])], p0 - 1, p1 + 1)
    pieces.append(plate)
    shape = union(pieces) ^ box(-30, 30, near0, far1, -20, 30)
    sx = c['slot_x_centre_mm']; sw = c['slot_width_mm']; sy0, sy1 = c['gate_slot_y_mm']; wall_x = sx + sw / 2; (rx, ry), ry1 = c['cap_ramp_start_xy_mm'], c['cap_ramp_end_y_mm']; lo_z = ft + .35
    for sign in (1, -1):
        shape -= box(min(0, sign * wall_x), max(0, sign * wall_x), sy0, sy1, lo_z, rt + 2)
        run = ry - ry1; shape -= base.prism_xy([(0, sy0 + .2), (sign * rx, sy0 + .2), (sign * rx, ry), (sign * (rx - run), ry1), (sign * (rx - run), ry1 - .6), (0, ry1 - .6)], lo_z, rt + 2)
    near, L, nr = base.arrow_ring(near0, near1, +1, P['rod']['ring_width']); far = base.ring((far0 + far1) / 2, None, P['rod']['ring_width'])
    end = nr[1] + .3; n = B19['near_saddle_narrow_half_x_mm']
    saddle = mf.Manifold.batch_hull([saddle_xz(kx, ft, a['saddle_bottom_z_mm'], near0, end, max_half=maxh), saddle_xz(n, ft, a['saddle_bottom_z_mm'], near0, end + (maxh - n), max_half=n + .01)])
    flank = prism_xz([(-kx, ft), (kx, ft), (sd, fb), (-sd, fb)], far0 - .5, far1)
    shape = (shape + saddle + flank) - base.corridor(); shape = shape + near + far; shape -= base.gap_cut(*nr); shape -= base.gap_cut(far0, far1)
    shape -= base.wire_bus(-80, 100); shape -= base.wire_bus(-80, 100).mirror((1, 0, 0))
    shape = spaces16.carve(shape, spaces16.regions('Battery_Holder'), 'battery')
    # The R18 door catch, unchanged: arrow roof, bar, pocket and chamfer.
    # The roof starts on the wall itself and grows inward at 45 degrees; R18's flange root would have begun as a 2.6 mm shelf over air here.
    b = D['bridge']; y = b['front_y_mm']; ra = B19['arrow_root_y_mm']; ap = ra - xi; assert abs(ap - (b['arrow_start_y_mm'] - c['roof_flange_inner_x_mm'])) < 1e-6
    arrow = prism_xy([(-xo, y), (xo, y), (xo, ra), (xi, ra), (0, ap), (-xi, ra), (-xo, ra)], rb, rt)
    shape += arrow; hw = b['pocket_half_x_mm']; shape -= box(-hw, hw, y - .5, b['pocket_back_y_mm'], rb - .05, b['pocket_ceiling_z_mm'])
    ch = b['chamfer_start_z_mm']; run = rt - ch; shape -= prism_yz([(y - .5, ch - .5), (y, ch), (y + run, rt), (y + run, rt + 1), (y - .5, rt + 1)], -hw, hw)
    return base.clean(shape, 'Battery_Holder')


@lru_cache(maxsize=1)
def sensor_holder():
    """Rails and keel joined by arrow-windowed cross bars in place of the R18 web. Board, keeper, USB and wire interfaces as R18."""
    s = S; a = P['arrow_ring']; z = BZ; rx0, rx1 = s['rail_x_mm']; rz0, rz1 = s['rail_z_mm']; y0, y1 = s['y_mm']; bo = s['board_outline_mm']; yn = s['board_near_end_y_mm']; yf = yn + bo['length']; inner = s['cradle_inner_x_mm']
