        # Lower outer corner of each keeper post: a triangle that carries nothing. Constant in Y, so it cannot start a layer over air.
        shape -= prism_xz([(sign * pc['x0_mm'], pc['z0_mm'] - 1), (sign * pc['x1_mm'], pc['z0_mm'] - 1), (sign * pc['x1_mm'], pc['z1_mm']), (sign * pc['x0_mm'], pc['z0_mm'])], y0 - 1, p['lead_end_y_mm'] + .2)
