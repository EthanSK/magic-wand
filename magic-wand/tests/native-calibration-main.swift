import Foundation
let folder=FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
defer{try? FileManager.default.removeItem(at:folder)}
let file=folder.appendingPathComponent("calibrations/first.json")
let bias=WandCalibration(x:-58.36,y:-172.84,z:5.72)
precondition(bias.valid)
try WandCalibrationStore.write(bias,to:file,device:"first")
precondition(WandCalibrationStore.read(file,device:"first")==bias)
precondition(WandCalibrationStore.read(file,device:"second")==nil)
let permissions=try FileManager.default.attributesOfItem(atPath:file.path)[.posixPermissions] as! NSNumber
precondition(permissions.intValue==0o600)
precondition(!WandCalibration(x:.nan,y:0,z:0).valid)
precondition(!WandCalibration(x:2000,y:0,z:0).valid)
let linked=file.deletingLastPathComponent().appendingPathComponent("linked.json")
try FileManager.default.createSymbolicLink(at:linked,withDestinationURL:file)
precondition(WandCalibrationStore.read(linked,device:"first")==nil)
try Data("bad data".utf8).write(to:file)
precondition(WandCalibrationStore.read(file,device:"first")==nil)
try WandCalibrationStore.write(bias,to:file,device:"second")
precondition(WandCalibrationStore.read(file,device:"first")==nil)
precondition(WandCalibrationStore.read(file,device:"second")==bias)
var sleep=WandDeskSleep()
for i in 0...599 {_=sleep.sample(parked:true,buttons:false,now:Double(i)/2)}
precondition(sleep.sleeping && !sleep.deepSleeping)
_=sleep.sample(parked:true,buttons:false,now:300)
precondition(sleep.deepSleeping)
_=sleep.sample(parked:true,buttons:true,now:300.1)
precondition(!sleep.deepSleeping && !sleep.sleeping)
_=sleep.sample(parked:true,buttons:false,now:301)
_=sleep.sample(parked:true,buttons:false,now:601)
precondition(!sleep.deepSleeping,"missing telemetry cannot prove five minutes of rest")
print("PASS calibration cache, device isolation, private permissions, corrupt data and deep-rest deadline")
